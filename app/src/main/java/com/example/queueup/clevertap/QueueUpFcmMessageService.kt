// PUSH MESSAGING SERVICE: Intercepts Firebase Cloud Messaging (FCM) push events and delegates to CleverTap.

package com.example.queueup.clevertap

import android.util.Log
import com.clevertap.android.sdk.CleverTapAPI
import com.clevertap.android.sdk.pushnotification.fcm.CTFcmMessageHandler
import com.google.firebase.messaging.FirebaseMessagingService
import com.google.firebase.messaging.RemoteMessage

class QueueUpFcmMessageService : FirebaseMessagingService() {

    // Invoked when an FCM push message arrives on the device.
    override fun onMessageReceived(remoteMessage: RemoteMessage) {
        super.onMessageReceived(remoteMessage)
        try {
            Log.d(TAG, "FCM message received from: ${remoteMessage.from}, data=${remoteMessage.data}")
            // CleverTap handles both standard notifications and rich Push Templates (Carousels, Timers, 5-icon, etc.)
            val handled = CTFcmMessageHandler().createNotification(applicationContext, remoteMessage)
            Log.d(TAG, "CleverTap processed push notification: $handled")
        } catch (t: Throwable) {
            Log.e(TAG, "Error rendering CleverTap push notification", t)
        }
    }

    // Invoked when a new FCM registration token is generated by Firebase.
    override fun onNewToken(token: String) {
        super.onNewToken(token)
        Log.d(TAG, "New Firebase Cloud Messaging registration token generated: $token")
        val sessionManager = com.example.queueup.network.SessionManager(applicationContext)
        sessionManager.saveFcmToken(token)
        // Register token with CleverTap instance for mobile push targeting
        CleverTapAPI.getDefaultInstance(applicationContext)?.pushFcmRegistrationId(token, true)
    }

    companion object {
        private const val TAG = "QueueUpFCM"
    }
}

